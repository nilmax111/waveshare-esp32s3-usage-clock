"""Build OFL-licensed Chinese glyph subset and calendar table. Requires Pillow."""
import json
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
root=Path(__file__).resolve().parent.parent
v=json.loads((root/'scripts/lunar_data.json').read_text())
chars=sorted(set(''.join(''.join(x) if isinstance(x,list) else x for k,x in v.items() if k!='_LUNAR')+'农历时辰刻闰年月传统计时参考'))
parser=argparse.ArgumentParser()
parser.add_argument('--font',required=True,help='Path to Noto Sans SC variable TTF')
args=parser.parse_args()
font=ImageFont.truetype(args.font,20)
font.set_variation_by_axes([500])
lines=['// Generated by scripts/build_lunar_assets.py; Noto Sans SC derived glyphs, SIL OFL 1.1; see third_party/NotoSansSC-OFL.txt.','#pragma once','#include <stdint.h>', 'static const uint32_t lunarYears[]={'+','.join(hex(x) for x in v['_LUNAR'])+'};']
for k in ('_STEMS','_BRANCHES','_ANIMALS','_MONTHS','_DAYS','_WEEK','_KES','_ORGANS','_ADVICE'):
 seq=list(v[k]) if isinstance(v[k],str) else v[k]
 lines.append('static const char* const '+k[1:].lower()+'[]={'+','.join(json.dumps(x,ensure_ascii=False) for x in seq)+'};')
lines+=['struct Glyph { uint16_t code; uint8_t bits[60]; };','static const Glyph lunarGlyphs[]={']
for c in chars:
 im=Image.new('1',(20,20));d=ImageDraw.Draw(im);d.text((0,17),c,font=font,fill=1,anchor='ls')
 data=[]
 for y in range(20):
  for byte in range(3):
   data.append(sum((128>>b) if byte*8+b<20 and im.getpixel((byte*8+b,y)) else 0 for b in range(8)))
 lines.append('{'+str(ord(c))+',{'+','.join(map(str,data))+'}},')
lines.append('};')
(root/'src/lunar_assets.h').write_text('\n'.join(lines)+'\n')
